impl Text {
    pub fn status_text(&self, phase: RunPhase) -> &'static str {
        match phase {
            RunPhase::Idle => self.status_idle,
            RunPhase::Monitoring => self.status_monitoring,
            RunPhase::Hit => self.status_hit,
        }
    }

    pub fn primary_label(&self, phase: RunPhase) -> &'static str {
        match phase {
            RunPhase::Idle => self.start_button,
            RunPhase::Monitoring => self.stop_button,
            RunPhase::Hit => self.unlock_button,
        }
    }
}

